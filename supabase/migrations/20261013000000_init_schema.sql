-- EliteChat Initial Schema & RLS Policies
-- Source: docs/database.md
-- Target: Supabase Postgres

-- 1. Types
create type public.conversation_type as enum ('direct', 'group');
create type public.member_role       as enum ('owner', 'admin', 'member');
create type public.message_kind      as enum ('text', 'image', 'file', 'system');
create type public.channel_role      as enum ('owner', 'admin', 'subscriber');
create type public.payment_status    as enum ('pending', 'confirmed', 'rejected');
create type public.subscription_status as enum ('active', 'expired', 'cancelled');

-- 2. Profiles
create table public.profiles (
  id           uuid primary key references auth.users(id) on delete cascade,
  handle       text unique check (handle ~ '^[a-z0-9_]{3,30}$'),
  display_name text check (char_length(display_name) between 1 and 60),
  avatar_path  text,
  bio          text check (char_length(bio) <= 280),
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- 3. Wallets
create table public.wallets (
  id               uuid primary key default gen_random_uuid(),
  user_id          uuid not null references public.profiles(id) on delete cascade,
  chain_namespace  text not null check (chain_namespace in ('eip155', 'solana')),
  address          text not null,            -- normalized lowercase for EVM
  is_primary       boolean not null default false,
  linked_at        timestamptz not null default now(),
  unique (chain_namespace, address)
);
create index wallets_user_idx on public.wallets (user_id);

-- 4. Auth Nonces (Service role only)
create table public.auth_nonces (
  nonce            text primary key,
  address          text not null,
  chain_namespace  text not null,
  domain           text not null,
  issued_at        timestamptz not null default now(),
  expires_at       timestamptz not null,
  used_at          timestamptz
);
create index auth_nonces_expires_idx on public.auth_nonces (expires_at);

-- 5. Conversations & Members
create table public.conversations (
  id              uuid primary key default gen_random_uuid(),
  type            public.conversation_type not null,
  title           text check (char_length(title) <= 100),
  avatar_path     text,
  direct_key      text unique,       -- 'uidA:uidB' sorted for direct chats
  created_by      uuid references public.profiles(id) on delete set null,
  last_message_at timestamptz,
  created_at      timestamptz not null default now(),
  check ((type = 'direct' and direct_key is not null) or type = 'group')
);

create table public.conversation_members (
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  user_id         uuid not null references public.profiles(id) on delete cascade,
  role            public.member_role not null default 'member',
  last_read_at    timestamptz,
  is_muted        boolean not null default false,
  joined_at       timestamptz not null default now(),
  primary key (conversation_id, user_id)
);
create index conv_members_user_idx on public.conversation_members (user_id);

-- 6. Messages & Attachments
create table public.messages (
  id              uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id       uuid not null references public.profiles(id) on delete cascade,
  client_id       uuid not null,     -- idempotency key generated by client
  kind            public.message_kind not null default 'text',
  content         text check (char_length(content) <= 4000),
  reply_to_id     uuid references public.messages(id) on delete set null,
  created_at      timestamptz not null default now(),
  edited_at       timestamptz,
  deleted_at      timestamptz,
  unique (conversation_id, client_id)
);
create index messages_conv_created_idx on public.messages (conversation_id, created_at desc);

create table public.attachments (
  id              uuid primary key default gen_random_uuid(),
  message_id      uuid not null references public.messages(id) on delete cascade,
  storage_path    text not null,
  file_name       text not null,
  mime_type       text not null,
  size_bytes      bigint not null check (size_bytes > 0),
  width           integer,
  height          integer,
  created_at      timestamptz not null default now()
);

-- 7. Channels & Channel Posts
create table public.channels (
  id              uuid primary key default gen_random_uuid(),
  slug            text unique check (slug ~ '^[a-z0-9-]{3,40}$'),
  title           text not null check (char_length(title) between 1 and 100),
  description     text check (char_length(description) <= 500),
  avatar_path     text,
  is_public       boolean not null default true,
  required_plan_id uuid,
  created_by      uuid references public.profiles(id) on delete set null,
  created_at      timestamptz not null default now()
);

create table public.channel_members (
  channel_id      uuid not null references public.channels(id) on delete cascade,
  user_id         uuid not null references public.profiles(id) on delete cascade,
  role            public.channel_role not null default 'subscriber',
  joined_at       timestamptz not null default now(),
  primary key (channel_id, user_id)
);

create table public.channel_posts (
  id              uuid primary key default gen_random_uuid(),
  channel_id      uuid not null references public.channels(id) on delete cascade,
  author_id       uuid not null references public.profiles(id) on delete cascade,
  content         text not null check (char_length(content) <= 10000),
  created_at      timestamptz not null default now()
);
create index channel_posts_idx on public.channel_posts (channel_id, created_at desc);

-- 8. Subscriptions & Payments
create table public.plans (
  id              uuid primary key default gen_random_uuid(),
  slug            text unique not null,
  title           text not null,
  description     text,
  price_amount    numeric(78,0) not null,
  price_token     text not null,
  duration_days   integer not null check (duration_days > 0),
  is_active       boolean not null default true,
  created_at      timestamptz not null default now()
);

create table public.payments (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null references public.profiles(id) on delete cascade,
  plan_id         uuid not null references public.plans(id),
  chain_namespace text not null,
  tx_hash         text not null,
  from_address    text not null,
  to_address      text not null,
  token_address   text,
  amount          numeric(78,0) not null,
  status          public.payment_status not null default 'pending',
  verified_at     timestamptz,
  created_at      timestamptz not null default now(),
  unique (chain_namespace, tx_hash)
);

create table public.subscriptions (
  id              uuid primary key default gen_random_uuid(),
  user_id         uuid not null references public.profiles(id) on delete cascade,
  plan_id         uuid not null references public.plans(id),
  payment_id      uuid references public.payments(id),
  starts_at       timestamptz not null default now(),
  expires_at      timestamptz not null,
  status          public.subscription_status not null default 'active'
);
create index subscriptions_user_idx on public.subscriptions (user_id, status);

-- 9. Blocks and Reports
create table public.blocks (
  blocker_id      uuid not null references public.profiles(id) on delete cascade,
  blocked_id      uuid not null references public.profiles(id) on delete cascade,
  created_at      timestamptz not null default now(),
  primary key (blocker_id, blocked_id)
);

create table public.reports (
  id              uuid primary key default gen_random_uuid(),
  reporter_id     uuid not null references public.profiles(id) on delete cascade,
  target_user_id  uuid references public.profiles(id) on delete cascade,
  target_msg_id   uuid references public.messages(id) on delete cascade,
  reason          text not null check (char_length(reason) between 5 and 500),
  status          text not null default 'pending',
  created_at      timestamptz not null default now()
);

-- ============================================================================
-- Row Level Security (RLS)
