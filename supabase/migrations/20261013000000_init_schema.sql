alter table public.profiles             enable row level security;
alter table public.wallets              enable row level security;
alter table public.auth_nonces          enable row level security;
alter table public.conversations        enable row level security;
alter table public.conversation_members enable row level security;
alter table public.messages             enable row level security;
alter table public.attachments          enable row level security;
alter table public.channels             enable row level security;
alter table public.channel_members      enable row level security;
alter table public.channel_posts        enable row level security;
alter table public.plans                enable row level security;
alter table public.payments             enable row level security;
alter table public.subscriptions        enable row level security;
alter table public.blocks               enable row level security;
alter table public.reports              enable row level security;

-- Profiles: Anyone authenticated can read profiles; owners can update own
create policy "Profiles readable by authenticated" on public.profiles
  for select to authenticated using (true);

create policy "Users update own profile" on public.profiles
  for update to authenticated using (id = auth.uid()) with check (id = auth.uid());

-- Wallets: Owners can read own wallets only (protects privacy)
create policy "Users read own wallets" on public.wallets
  for select to authenticated using (user_id = auth.uid());

-- Conversations: Members can read conversations
create policy "Members read conversations" on public.conversations
  for select to authenticated using (
    exists (
      select 1 from public.conversation_members cm
      where cm.conversation_id = id and cm.user_id = auth.uid()
    )
  );

-- Conversation Members: Members can read roster
create policy "Members read conversation members" on public.conversation_members
  for select to authenticated using (
    exists (
      select 1 from public.conversation_members me
      where me.conversation_id = conversation_id and me.user_id = auth.uid()
    )
  );

create policy "Users update own membership" on public.conversation_members
  for update to authenticated using (user_id = auth.uid());

-- Messages: Members can read; sender inserts
create policy "Members read messages" on public.messages
  for select to authenticated using (
    exists (
      select 1 from public.conversation_members cm
      where cm.conversation_id = conversation_id and cm.user_id = auth.uid()
    ) and deleted_at is null
  );

create policy "Members insert messages" on public.messages
  for insert to authenticated with check (
    sender_id = auth.uid() and
    exists (
      select 1 from public.conversation_members cm
      where cm.conversation_id = conversation_id and cm.user_id = auth.uid()
    )
  );

-- Channels & Posts
create policy "Public channels readable" on public.channels
  for select to authenticated using (is_public = true or exists (
    select 1 from public.channel_members cm where cm.channel_id = id and cm.user_id = auth.uid()
  ));

create policy "Channel members read posts" on public.channel_posts
  for select to authenticated using (
    exists (
      select 1 from public.channel_members cm
      where cm.channel_id = channel_id and cm.user_id = auth.uid()
    )
  );

-- Plans & Subscriptions
create policy "Plans readable by all" on public.plans
  for select to authenticated using (is_active = true);

create policy "Users view own subscriptions" on public.subscriptions
  for select to authenticated using (user_id = auth.uid());

create policy "Users view own payments" on public.payments
  for select to authenticated using (user_id = auth.uid());

-- Blocks
create policy "Users manage own blocks" on public.blocks
  for all to authenticated using (blocker_id = auth.uid());
